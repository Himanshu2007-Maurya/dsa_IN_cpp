// ======================================================
// C++ BOILERPLATE CODE
// This is the basic structure of a C++ program.
// ======================================================


// 1. Include Header File
// iostream is used for input and output.
// Example: cin and cout
#include <iostream>


// 2. Use Standard Namespace
// This allows us to write cout instead of std::cout
// and cin instead of std::cin.
using namespace std;


// 3. Main Function
// Program execution starts from the main() function.
int main()
{
    // --------------------------------------------------
    // 4. Output
    // cout is used to print something on the screen.
    // --------------------------------------------------
    cout << "Hello, World!" << endl;


    // --------------------------------------------------
    // 5. Return Statement
    // return 0 means the program finished successfully.
    // --------------------------------------------------
    return 0;
}